    public function run(): void
    {
        DB::disableQueryLog();

        DB::transaction(function (): void {
            foreach ($this->data() as $table => $rows) {
                if (! Schema::hasTable($table) || $rows === []) {
                    continue;
                }

                foreach (array_chunk($rows, 100) as $chunk) {
                    $chunk = $this->normaliseJsonColumns($table, $chunk);
                    $columns = array_keys($chunk[0]);
                    $updateColumns = array_values(array_diff($columns, ['id']));

                    DB::table($table)->upsert($chunk, ['id'], $updateColumns);
                }

                $this->command?->line("Seeded {$table}: " . count($rows));
            }
        });
    }

    private function normaliseJsonColumns(string $table, array $rows): array
    {
        $jsonColumns = self::JSON_COLUMNS[$table] ?? [];

        if ($jsonColumns === []) {
            return $rows;
        }

        foreach ($rows as &$row) {
            foreach ($jsonColumns as $column) {
                if (array_key_exists($column, $row) && is_array($row[$column])) {
                    $row[$column] = json_encode($row[$column], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
                }
            }
        }

        return $rows;
    }

